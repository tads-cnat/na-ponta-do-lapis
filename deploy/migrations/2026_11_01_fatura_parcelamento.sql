-- -----------------------------------------------------------------------------
-- 1. Padrões globais de leitura de fatura (compartilhados entre usuários)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS padrao_fatura (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emissor             VARCHAR(100) NOT NULL,
    regex_identificacao VARCHAR(500) NOT NULL,
    regex_transacao     VARCHAR(1000) NOT NULL,
    regex_total         VARCHAR(500),
    formato_data        VARCHAR(30) NOT NULL,
    versao              INTEGER NOT NULL DEFAULT 1,
    origem              VARCHAR(20) NOT NULL DEFAULT 'SEED',
    ativo               BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em       TIMESTAMP
);

-- Garante no máximo um padrão ativo por emissor.
CREATE UNIQUE INDEX IF NOT EXISTS ux_padrao_fatura_emissor_ativo
    ON padrao_fatura (emissor)
    WHERE ativo = TRUE;

-- -----------------------------------------------------------------------------
-- 2. Metadados de parcelamento na transação
-- -----------------------------------------------------------------------------
ALTER TABLE transacao
    ADD COLUMN IF NOT EXISTS grupo_parcelamento VARCHAR(36);

ALTER TABLE transacao
    ADD COLUMN IF NOT EXISTS numero_parcela INTEGER;

ALTER TABLE transacao
    ADD COLUMN IF NOT EXISTS total_parcelas INTEGER;

ALTER TABLE transacao
    ADD COLUMN IF NOT EXISTS valor_total_compra NUMERIC(19, 2);

-- Busca das parcelas de um mesmo grupo (listagem, geração e exclusão).
CREATE INDEX IF NOT EXISTS ix_transacao_grupo_parcelamento
    ON transacao (grupo_parcelamento);

